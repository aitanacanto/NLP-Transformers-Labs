import os
os.environ["TF_ENABLE_ONEDNN_OPTS"] = "0"

import torch

from transformers import AutoModelForCausalLM, AutoTokenizer, logging

logging.set_verbosity_error()

checkpoint = "HuggingFaceTB/SmolLM2-135M-Instruct"
tokeniser = AutoTokenizer.from_pretrained(checkpoint)
model = AutoModelForCausalLM.from_pretrained(checkpoint)

def messages_to_string(messages:list[dict]) -> str:
    # Task 1
    # Return a string with the tokeniser's template applied.
    return tokeniser.apply_chat_template(messages, tokenize=False)

def tokenise_messages(messages:list[dict]) -> torch.Tensor:
    # Task 2
    # Return a PyTorch Tensor encoded by the tokeniser.
    text = messages_to_string(messages)  # Convert to string
    return tokeniser.encode(text, return_tensors="pt")  # Tokanize

def generate_once(input_tensor:torch.Tensor, max_new_tokens:int=32) -> torch.Tensor:
    # Task 3
    # Return a PyTorch Tensor generated by the model up to a set number of new tokens.
    return model.generate(
        input_tensor,
        max_new_tokens=max_new_tokens,
        temperature=0.7,
        top_p=0.9,
        do_sample=True
    )

def decode_outputs(output_tensor:torch.Tensor) -> str:
    return tokeniser.decode(output_tensor[0])

def generate_complete(input_tensor:torch.Tensor, max_new_tokens:int=32) -> torch.Tensor:
    # Task 4
    # Return a PyTorch Tensor generated by the model up to a message's completion.
    output_tensor = input_tensor
    while True:
        output_tensor = generate_once(output_tensor, max_new_tokens=max_new_tokens)
        decoded_text = decode_outputs(output_tensor)
        if "<|im_end|>" in decoded_text:
            break
    return output_tensor

def converse(messages:list[dict]):
    for i in messages:
        print(f"{i['role']}:\n{i['content']}")
    input_tensor = tokenise_messages(messages)
    existing_length = input_tensor.shape[1]
    if messages[-1]["role"] == "user":
        input_tensor = generate_complete(input_tensor)
        print("assistant:", decode_outputs(input_tensor[:, existing_length:]).removeprefix("<|im_start|>assistant\n").removesuffix("<|im_end|>"), sep="\n")
    while True:
        user_input = input("user:\n")
        if user_input.lower() == "exit":
            return
        
        # Task 5
        # Generate and print the model's response to user input.
        user_text = f"<|im_start|>user\n{user_input}<|im_end|>\n"
        user_tensor = tokeniser.encode(user_text, return_tensors="pt")
        input_tensor = torch.cat([input_tensor, user_tensor], dim=1)
        existing_length = input_tensor.shape[1]
        input_tensor = generate_complete(input_tensor)
        assist_text = decode_outputs(input_tensor[:, existing_length:])
        assist_text = assist_text.removeprefix("<|im_start|>assistant\n").removesuffix("<|im_end|>")
        print("assistant:", assist_text, sep="\n")

